        seed ^= (seed << 6) + (seed >> 2) + 0x42AA2E06 + std::hash<QuadrupleArg>()(obj.arg1);
        seed ^= (seed << 6) + (seed >> 2) + 0x60D503AC + std::hash<QuadrupleArg>()(obj.arg2);
