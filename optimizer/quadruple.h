// arg types: constant, bb_temp, [ptr+offset]

// ======================== in parser ==============================
// halt            -    -    -
// ptr_add         - arg1    -    ptr += arg1
// add        result arg1 arg2    result = arg1 + arg2
// sub        result arg1 arg2    result = arg1 - arg2
// mul        result arg1 arg2    result = arg1 * arg2
// neg        result arg1    -    result = -arg1 即 (~arg1 + 1)
// assign     result arg1    -    result = arg1
// jnz             - arg1 arg2    if (arg1) goto imm_arg2
// jz              - arg1 arg2    if (!arg1) goto imm_arg2
// jmp             -    - arg2    goto imm_arg2
// putchar         - arg1    -    putchar(arg1)
// getchar    result    -    -    result = getchar()


// 其实 jnz 和 jz 在基本块内没区别，无非就是交换一下 succY 和 succN，但是已经写完了，不改了
// ======================= in basic block ==========================
// ptr_add        - arg1    -    ptr += arg1
// add       result arg1 arg2    result = arg1 + arg2
// sub       result arg1 arg2    result = arg1 - arg2
// mul       result arg1 arg2    result = arg1 * arg2
// neg       result arg1    -    result = -arg1
// assign    result arg1    -    result = arg1
// jnz            - arg1    -    if (arg1) goto succY else goto succN
// jz             - arg1    -    if (!arg1) goto succY else goto succN
// putchar        - arg1    -    putchar(arg1)
// getchar   result    -    -    result = getchar()

struct QuadrupleArg {
    enum class ArgType {
        NIL = 0, PTR_OFFSET, BB_TEMP, CONSTANT
    };

    ArgType type;
    int32_t value;

    static const char * const ARG_TYPE_TRANSLATE[4];

    auto operator<=>(const QuadrupleArg&) const = default;

    friend std::ostream & operator<<(std::ostream &os, const QuadrupleArg &obj) {
        switch (obj.type) {
            case ArgType::BB_TEMP:
                os << 'T' << obj.value;
                break;
            case ArgType::PTR_OFFSET:
                if (obj.value >= 0) {
                    os << "[PTR + " << obj.value << ']';
                } else {
                    os << "[PTR - " << -obj.value << ']';
                }
                break;
            case ArgType::CONSTANT:
                os << obj.value;
                break;
            default:
                os << "--";
        }
        return os;
    }
};

template <>
struct std::hash<QuadrupleArg> {
    // generated by clion
    std::size_t operator()(const QuadrupleArg &obj) const noexcept {
        std::size_t seed = 0x5391975B;
        seed ^= (seed << 6) + (seed >> 2) + 0x1FF02B85 + static_cast<std::size_t>(obj.type);
        seed ^= (seed << 6) + (seed >> 2) + 0x6AF83FDE + static_cast<std::size_t>(obj.value);
        return seed;
    }
};

struct Quadruple {
    enum class OpType {
        HALT = 0, PTR_ADD, ADD, SUB, MUL, NEG, ASSIGN, JNZ, JZ, JMP, PUTCHAR, GETCHAR
    };

    struct CSECanonicalKey {
        OpType type;
        QuadrupleArg arg1;
        QuadrupleArg arg2;

        auto operator<=>(const CSECanonicalKey&) const = default;
    };

    struct MergeRule {
        bool (*cond)(const Quadruple& current, const Quadruple& other);
        void (*actionMod256)(Quadruple& current, const Quadruple& other);
    };

    struct SingleSimpRule {
        bool (*cond)(const Quadruple& current);
        void (*actionMod256)(Quadruple& current);
    };

    OpType type;
    QuadrupleArg result;
    QuadrupleArg arg1;
    QuadrupleArg arg2;

    static const char * const CODE_TYPE_TRANSLATE[12];

    // constant in add and mul must in arg2

    static const std::array<SingleSimpRule, 13> SINGLE_SIMP_RULES;
    static const std::array<MergeRule, 24> MERGE_RULES;

    auto operator<=>(const Quadruple&) const = default;

    [[nodiscard]] CSECanonicalKey toCanonicalKey() const {
        if ((type == OpType::ADD || type == OpType::MUL) && arg1 > arg2) {
            return {type, arg2, arg1};
        }
        return {type, arg1, arg2};
    }

    // 基于预定义规则化简单条四元式
    // 有一些变换可能导致 x86 flags 设置情况不同，但通常来说不影响 ZF
    void preSimplifyMod256() {
        using ArgType = QuadrupleArg::ArgType;
        // 预先模 256
        if (type != OpType::PTR_ADD) {
            if (arg1.type == ArgType::CONSTANT) {
                arg1.value = static_cast<int8_t>(arg1.value);
            }
            if (arg2.type == ArgType::CONSTANT) {
                arg2.value = static_cast<int8_t>(arg2.value);
            }
        }
        // 预先把加法和乘法的常量换到第二参数
        if ((type == OpType::ADD || type == OpType::MUL) && arg1.type == ArgType::CONSTANT) {
            std::swap(arg1, arg2);
        }
        for (auto &simpRule : SINGLE_SIMP_RULES) {
            if (simpRule.cond(*this)) {
                simpRule.actionMod256(*this);
                return;
            }
        }
    }

    // 基于预定义规则合并两条四元式
    // 有一些变换可能导致 x86 flags 设置情况不同，但通常来说不影响 ZF
    // 成功返回 true
    // must pre simplified
    // no [const op const]
    // constant in add and mul must in arg2
    bool mergeMod256(const Quadruple &other) {
        using ArgType = QuadrupleArg::ArgType;
        if (other.result.type != ArgType::BB_TEMP) {
            return false;
        }
        for (auto &mergeRule : MERGE_RULES) {
            if (mergeRule.cond(*this, other)) {
                mergeRule.actionMod256(*this, other);
                return true;
            }
        }
        return false;
    }

    friend std::ostream & operator<<(std::ostream &os, const Quadruple &obj) {
        return os << CODE_TYPE_TRANSLATE[static_cast<int>(obj.type)] << '\t' << obj.result << ", " << obj.arg1 << ", " << obj.arg2;
    }
};

template<>
struct std::hash<Quadruple> {
    // generated by clion
    std::size_t operator()(const Quadruple &obj) const noexcept {
        std::size_t seed = 0x372C7D5B;
        seed ^= (seed << 6) + (seed >> 2) + 0x5963F183 + static_cast<std::size_t>(obj.type);
        seed ^= (seed << 6) + (seed >> 2) + 0x0C595278 + std::hash<QuadrupleArg>()(obj.result);
        seed ^= (seed << 6) + (seed >> 2) + 0x721FD60E + std::hash<QuadrupleArg>()(obj.arg1);
        seed ^= (seed << 6) + (seed >> 2) + 0x6F329F6F + std::hash<QuadrupleArg>()(obj.arg2);
        return seed;
    }
};

