WindowsPEPlusGenerator::WindowsPEPlusGenerator(const std::vector<std::unique_ptr<MidBasicBlock>>& basicBlocks, int32_t tapeSize, int32_t initOffset) :
    m_tapeSize(tapeSize), m_initOffset(initOffset), m_needGetchar(false) {
    std::unordered_map<MidBasicBlock*, X64BasicBlock*> mapper;
    m_basicBlocks.reserve(basicBlocks.size());
    for (auto& block : basicBlocks) {
        m_basicBlocks.emplace_back(std::make_unique<X64BasicBlock>());
        mapper[block.get()] = m_basicBlocks.back().get();
        m_basicBlocks.back()->setIRs(std::move(block->irs));
    }
    for (auto& block : basicBlocks) {
        auto* x64Block = mapper[block.get()];
        for (auto* pred : block->preds) {
            x64Block->addPred(mapper[pred]);
        }
        x64Block->setSuccY(mapper[block->succY]);
        x64Block->setSuccN(mapper[block->succN]);
    }

    // 程序一定要输出（putchar 的寄存器永远保留）
    // getchar 可能就不需要了
    for (auto& block : m_basicBlocks) {
        block->setCanUseGetcharReg(true);
        if (block->hasGetchar()) {
            m_needGetchar = true;
            break;
        }
    }

    if (m_needGetchar) {
        // 倒序遍历 m_basicBlocks，看哪些基本块能安全顶掉 getchar 的寄存器
        bool change;
        do {
            change = false;
            for (auto& block : m_basicBlocks | std::views::reverse) {
                if (!block->canUseGetcharReg()) {
                    for (auto* pred : block->preds()) {
                        if (pred->canUseGetcharReg()) {
                            pred->setCanUseGetcharReg(false);
                            change = true;
                        }
                    }
                } else if (block->hasGetchar()) {
                    block->setCanUseGetcharReg(false);
                    for (auto* pred : block->preds()) {
                        pred->setCanUseGetcharReg(false);
                    }
                    change = true;
                }
            }
        } while (change);
    }
}

int32_t WindowsPEPlusGenerator::countASMs() const {
	int32_t cnt = 0;
	for (auto& block : m_basicBlocks) {
		cnt += block->asms().size();
	}
	return cnt;
}

void WindowsPEPlusGenerator::rearrangeIRs(bool printInfo) const {
	int32_t cnt = 0;
    for (auto& block : m_basicBlocks) {
        cnt += block->rearrange();
    }
	if (printInfo) {
		std::cout << "rearrange: numIR = " << cnt << '\n';
	}
}

void WindowsPEPlusGenerator::generate(OptimizationLevel level, bool isModern, bool printInfo, std::ostream& os) {
    generateASM(level, printInfo);
    placeBasicBlocks();
	setBlocksRelJmp();
    writeTo(os, isModern);
	if (printInfo) {
		std::cout << "numASM = " << countASMs() << '\n';
	}
}

void WindowsPEPlusGenerator::generateASM(OptimizationLevel level, bool printInfo) const {
	if (level != OptimizationLevel::O0) {
		rearrangeIRs(printInfo);
	}
    for (auto& block : m_basicBlocks) {
        block->generateWindows(level);
    }
}

void WindowsPEPlusGenerator::placeBasicBlocks() {
    m_orderedBlocks.clear();
    std::unordered_set<X64BasicBlock*> vis;
    std::vector<X64BasicBlock*> stack;

    vis.insert(m_basicBlocks[0].get());
    stack.push_back(m_basicBlocks[0].get());

    while (!stack.empty()) {
        auto* block = stack.back();
        stack.pop_back();
        m_orderedBlocks.push_back(block);
        auto *succY = block->succY();
        auto *succN = block->succN();
        if (succY == nullptr) {
            if (succN != nullptr) {
                // 单分支
                if (vis.contains(succN)) {
                    // 已经被访问过了，必须生成一条跳转，不必放置
                    block->placeJmp();
                } else {
                    // 否则直落
                    vis.insert(succN);
                    stack.push_back(succN);
                }
            }
        } else {
            // 双分支，假设 jcc 的跳转目标是 succY
            if (vis.contains(succN) && vis.contains(succY)) {
                // 如果两个都被访问过了，那很享受了，一条 jcc 加 jmp 吧，不翻转 jcc
                block->placeJmp();
            } else if (vis.contains(succN)) {
                // 如果 succN 被访问而 succY 未被访问，翻转 jcc，直落 succY
                block->equivFlipCondJmp();
                vis.insert(succY);
                stack.push_back(succY);
            } else if (vis.contains(succY)) {
                // 如果 succY 被访问而 succN 未被访问，直落 succN
                vis.insert(succN);
                stack.push_back(succN);
            } else {
                // 找 if 模式进行简单的优化，if-else 就摆烂生成垃圾代码吧
                if (succY->succY() == succN || succY->succN() == succN) {
                    // 翻转 jcc
                    block->equivFlipCondJmp();
                    // 先不放置 succN
                    vis.insert(succN);
                    stack.push_back(succN);
                    // 直落 succY，后压栈先遍历
                    vis.insert(succY);
                    stack.push_back(succY);
                } else {
                    // 先不放置 succY
                    vis.insert(succY);
                    stack.push_back(succY);
                    // 直落 succN，后压栈先遍历
                    vis.insert(succN);
                    stack.push_back(succN);
                }
            }
        }
    }

    // 填写跳转到基本块的编号
    std::unordered_map<X64BasicBlock*, int32_t> idMap;
    int32_t id = 0;
    for (auto* block : m_orderedBlocks) {
        idMap[block] = id++;
    }
    for (auto* block : m_orderedBlocks) {
        block->setJmpTarget(idMap);
    }
    for (int32_t j = 0, size = m_orderedBlocks.size(); j < size; j++) {
        m_orderedBlocks[j]->removeJmpIfJmpTo(j + 1);
    }
}

void WindowsPEPlusGenerator::setBlocksRelJmp() const {
	for (auto* block : m_orderedBlocks) {
		block->firstCalcCodeSize();
	}
	auto codePos = std::make_unique<int32_t[]>(m_orderedBlocks.size());
	bool changed;
	do {
		int32_t ip = 0;
		for (int32_t i = 0, size = m_orderedBlocks.size(); i < size; i++) {
			codePos[i] = ip;
			ip += m_orderedBlocks[i]->codeSize();
		}
		changed = false;
		for (int32_t i = 0, size = m_orderedBlocks.size(); i < size; i++) {
			if (m_orderedBlocks[i]->tryShortJmp(i, codePos.get())) {
				changed = true;
			}
		}
	} while (changed);
	for (int32_t i = 0, size = m_orderedBlocks.size(); i < size; i++) {
		m_orderedBlocks[i]->finalSetJmpRel(i, codePos.get());
	}
}

void WindowsPEPlusGenerator::writeTo(std::ostream& os, bool isModern) const {
    if (isModern) {
        modernWriteTo(os);
    } else {
        legacyWriteTo(os);
    }
}

void WindowsPEPlusGenerator::legacyWriteTo(std::ostream& os) const {
    X64EncodingCtx ctx;
    // 设置初始指针位置
    if (m_tapeSize > 0) {
        if (m_initOffset != 0) {
            ctx.emit({
                X64Asm::Operator::LEA,
                X64RMOperand{false, X64RMOperand::Size::QWORD, X64RMOperand::Reg::BX},
                X64RMOperand{true, X64RMOperand::Size::QWORD, X64RMOperand::Reg::AX, m_initOffset}
            }, false);
        } else {
            ctx.emit({
                X64Asm::Operator::MOV,
                X64RMOperand{false, X64RMOperand::Size::QWORD, X64RMOperand::Reg::BX},
                X64RMOperand{false, X64RMOperand::Size::QWORD, X64RMOperand::Reg::AX}
            }, false);
        }
    }

    // 编码
    for (auto* block : m_orderedBlocks) {
        block->finalEncode(ctx);
    }

    // 设置关键大小
    int32_t codeActualSize = ctx.size() + LEGACY_NORMAL_PART_LEN + (m_needGetchar ? LEGACY_GETCHAR_PART_LEN : 0) + (m_tapeSize > 0 ? LEGACY_CALLOC_PART_LEN : 0);
    int32_t codeSizeCeil512 = (codeActualSize + 511) & ~511;
    *reinterpret_cast<int32_t*>(s_legacyPEPlusRuntimeData.data() + LEGACY_SIZE_OF_CODE_OFFSET) = codeSizeCeil512;
    *reinterpret_cast<int32_t*>(s_legacyPEPlusRuntimeData.data() + LEGACY_SIZE_OF_IMAGE_OFFSET) = 4096 + ((codeSizeCeil512 + 4095) & ~4095);
    *reinterpret_cast<int32_t*>(s_legacyPEPlusRuntimeData.data() + LEGACY_TEXT_VIRTUAL_SIZE_OFFSET) = codeActualSize;
    *reinterpret_cast<int32_t*>(s_legacyPEPlusRuntimeData.data() + LEGACY_TEXT_RAW_SIZE_OFFSET) = codeSizeCeil512;

    // 写入 pe 头和启动代码
    os.write(reinterpret_cast<const char*>(s_legacyPEPlusRuntimeData.data()), LEGACY_GETCHAR_PART_OFFSET);
    if (m_needGetchar) {
        // 如果需要 getchar 则写入获取 getchar 的代码
        os.write(reinterpret_cast<const char*>(s_legacyPEPlusRuntimeData.data() + LEGACY_GETCHAR_PART_OFFSET), LEGACY_GETCHAR_PART_LEN);
    }
    if (m_tapeSize > 0) {
        // 如果需要数组则设置数组长度并写入 calloc 的代码
        *reinterpret_cast<int32_t*>(s_legacyPEPlusRuntimeData.data() + LEGACY_CALLOC_ARRAY_SIZE_OFFSET) = m_tapeSize;
        os.write(reinterpret_cast<const char*>(s_legacyPEPlusRuntimeData.data() + LEGACY_CALLOC_PART_OFFSET), LEGACY_CALLOC_PART_LEN);
    }
    // 写入剩下的代码
    os.write(reinterpret_cast<const char*>(ctx.data()), ctx.size());
    // 0 填充对齐
    os.write(std::string(codeSizeCeil512 - codeActualSize, 0).data(), codeSizeCeil512 - codeActualSize);
}

void WindowsPEPlusGenerator::modernWriteTo(std::ostream& os) const {
    // 编码
    X64EncodingCtx ctx;
    for (auto* block : m_orderedBlocks) {
        block->finalEncode(ctx);
    }
    // 设置头
    int32_t codeActualSize = ctx.size() + s_modernPEPlusInitInsts.size();
    int32_t codeSizeCeil512 = (codeActualSize + 511) & ~511;
    int32_t codeSizeCeil4096 = (codeActualSize + 4095) & ~4095;
    int32_t tapeSize = std::max(1, m_tapeSize);
    int32_t tapeSizeCeil512 = (tapeSize + 511) & ~511;
    int32_t tapeSizeCeil4096 = (tapeSize + 4095) & ~4095;
    int32_t rDataVirtAddr = 0x1000 + codeSizeCeil4096;
    int32_t rDataRawAddr = 0x400 + codeSizeCeil512;
    *reinterpret_cast<int32_t*>(s_modernPEPlusHeader.data() + MODERN_SIZE_OF_CODE_OFFSET) = codeSizeCeil512;
    *reinterpret_cast<int32_t*>(s_modernPEPlusHeader.data() + MODERN_SIZE_OF_INITIALIZED_DATA_OFFSET) = 512 + tapeSizeCeil512;
    *reinterpret_cast<int32_t*>(s_modernPEPlusHeader.data() + MODERN_SIZE_OF_IMAGE_OFFSET) = 8192 + codeSizeCeil4096 + tapeSizeCeil4096;
    *reinterpret_cast<int32_t*>(s_modernPEPlusHeader.data() + MODERN_IMPORT_DIRECTORY_RVA_OFFSET) = rDataVirtAddr + 0x138;
    *reinterpret_cast<int32_t*>(s_modernPEPlusHeader.data() + MODERN_DEBUG_DIRECTORY_RVA_OFFSET) = rDataVirtAddr + 0x28;
    *reinterpret_cast<int32_t*>(s_modernPEPlusHeader.data() + MODERN_IMPORT_ADDRESS_TABLE_DIRECTORY_RVA_OFFSET) = rDataVirtAddr;
    *reinterpret_cast<int32_t*>(s_modernPEPlusHeader.data() + MODERN_TEXT_VIRTUAL_SIZE_OFFSET) = codeActualSize;
    *reinterpret_cast<int32_t*>(s_modernPEPlusHeader.data() + MODERN_TEXT_RAW_SIZE_OFFSET) = codeSizeCeil512;
    *reinterpret_cast<int32_t*>(s_modernPEPlusHeader.data() + MODERN_RDATA_VIRTUAL_ADDRESS_OFFSET) = rDataVirtAddr;
    *reinterpret_cast<int32_t*>(s_modernPEPlusHeader.data() + MODERN_RDATA_RAW_ADDRESS_OFFSET) = rDataRawAddr;
    *reinterpret_cast<int32_t*>(s_modernPEPlusHeader.data() + MODERN_DATA_VIRTUAL_SIZE_OFFSET) = tapeSize;
    *reinterpret_cast<int32_t*>(s_modernPEPlusHeader.data() + MODERN_DATA_VIRTUAL_ADDRESS_OFFSET) = 0x2000 + codeSizeCeil4096;
    // 写入头
    os.write(reinterpret_cast<const char*>(s_modernPEPlusHeader.data()), s_modernPEPlusHeader.size());
    // 填充到 0x400
    os.write(std::string(0x400 - s_modernPEPlusHeader.size(), 0).data(), 0x400 - s_modernPEPlusHeader.size());
    // 设置 rip 寻址
    *reinterpret_cast<int32_t*>(s_modernPEPlusInitInsts.data() + MODERN_MOV_EXIT_PROCESS_RIP_RELATIVE_OFFSET) = 0xff5 + codeSizeCeil4096 - 0x1000;
    *reinterpret_cast<int32_t*>(s_modernPEPlusInitInsts.data() + MODERN_MOV_PUTCHAR_RIP_RELATIVE_OFFSET) = 0x1006 + codeSizeCeil4096 - 0x1000;
    *reinterpret_cast<int32_t*>(s_modernPEPlusInitInsts.data() + MODERN_MOV_GETCHAR_RIP_RELATIVE_OFFSET) = 0xff7 + codeSizeCeil4096 - 0x1000;
    *reinterpret_cast<int32_t*>(s_modernPEPlusInitInsts.data() + MODERN_LEA_PTR_RIP_RELATIVE_OFFSET) = 0xfdb + codeSizeCeil4096 + m_initOffset;
    // 写入起始指令
    os.write(reinterpret_cast<const char*>(s_modernPEPlusInitInsts.data()), s_modernPEPlusInitInsts.size());
    // 写入剩下的代码
    os.write(reinterpret_cast<const char *>(ctx.data()), ctx.size());
    // 0 填充对齐
    os.write(std::string(codeSizeCeil512 - codeActualSize, 0).data(), codeSizeCeil512 - codeActualSize);
    // 设置 rdata
    *reinterpret_cast<int32_t*>(s_modernPEPlusRData.data() + MODERN_DEBUG_ADDRESS_OF_RAW_DATA_OFFSET) = rDataVirtAddr + 0x5c;
    *reinterpret_cast<int32_t*>(s_modernPEPlusRData.data() + MODERN_DEBUG_POINTER_TO_RAW_DATA) = rDataRawAddr + 0x5c;
    *reinterpret_cast<int32_t*>(s_modernPEPlusRData.data() + MODERN_IMPORT_KERNEL32_OFTS) = rDataVirtAddr + 0x178;
    *reinterpret_cast<int32_t*>(s_modernPEPlusRData.data() + MODERN_IMPORT_KERNEL32_NAME_RVA) = rDataVirtAddr + 0x1ae;
    *reinterpret_cast<int32_t*>(s_modernPEPlusRData.data() + MODERN_IMPORT_KERNEL32_FTS) = rDataVirtAddr;
    *reinterpret_cast<int32_t*>(s_modernPEPlusRData.data() + MODERN_IMPORT_STDIO_OFTS) = rDataVirtAddr + 0x188;
    *reinterpret_cast<int32_t*>(s_modernPEPlusRData.data() + MODERN_IMPORT_STDIO_NAME_RVA) = rDataVirtAddr + 0x1d0;
    *reinterpret_cast<int32_t*>(s_modernPEPlusRData.data() + MODERN_IMPORT_STDIO_FTS) = rDataVirtAddr + 0x10;
    *reinterpret_cast<int64_t*>(s_modernPEPlusRData.data() + MODERN_IMPORT_EXIT_PROCESS_OFTS) = rDataVirtAddr + 0x1a0;
    *reinterpret_cast<int64_t*>(s_modernPEPlusRData.data() + MODERN_IMPORT_EXIT_PROCESS_FTS) = rDataVirtAddr + 0x1a0;
    *reinterpret_cast<int64_t*>(s_modernPEPlusRData.data() + MODERN_IMPORT_GETCHAR_OFTS) = rDataVirtAddr + 0x1c6;
    *reinterpret_cast<int64_t*>(s_modernPEPlusRData.data() + MODERN_IMPORT_GETCHAR_FTS) = rDataVirtAddr + 0x1c6;
    *reinterpret_cast<int64_t*>(s_modernPEPlusRData.data() + MODERN_IMPORT_PUTCHAR_OFTS) = rDataVirtAddr + 0x1bc;
    *reinterpret_cast<int64_t*>(s_modernPEPlusRData.data() + MODERN_IMPORT_PUTCHAR_FTS) = rDataVirtAddr + 0x1bc;
    // 写入 rdata
    os.write(reinterpret_cast<const char*>(s_modernPEPlusRData.data()), s_modernPEPlusRData.size());
}

void WindowsPEPlusGenerator::printIRAndASM() const {
    int32_t i = 0;
    int32_t ip = 0;
    for (auto* block : m_orderedBlocks) {
        std::cout << "id=" << i << ", ip=" << ip << '\n';
        std::cout << *block << "\n\n";
        i++;
        ip += block->codeSize();
    }
}
