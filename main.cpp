#include <filesystem>
#include <iostream>
#include <fstream>

#include "interpreter/interpreter.h"
#include "generator/windows_pe_plus_generator.h"
#include "optimizer/code_optimizer.h"
#include "parser/neo_parser.h"

static const char * const HELP_STR =
    "OVERVIEW: Brainfuck compiler\n\n"
    "USAGE: bf-compiler.exe [options] file...\n\n"
    "OPTIONS:\n"
    "  --help                  Display available options\n"
    "  --mem-size <value>      Set the runtime memory size. The unit is bytes, with a range of 1 to 2147483647, and the default is 80000000. This does not include the guard space generated by aggressive optimization. When optimization is enabled and the pointer position is globally determinable, this option is automatically ignored.\n"
    "  -O0                     Disable optimization\n"
    "  -O1                     Enable optimization. This option is enabled by default.\n"
    "  --optimize-strict       Be conservative in optimization and no guard space is generated\n"
    "  -o <file>               Write output to <file>\n"
    "  --out-c                 Output C instead of PE\n"
    "  --out-legacy-pe         Output \"legacy\" PE (may be detected as a virus)\n"
    "  --print-info            Print optimization and generation information\n"
    "  --version               Print version information\n";

static const char * const VER_STR = "Yet Another Neo Brainfuck Compiler version 1.0.0\nTarget: x86_64-pc-windows\n";

static std::unordered_map<std::wstring_view, std::wstring_view> getOpts(int argc, wchar_t* argv[]) {
    std::unordered_map<std::wstring_view, std::wstring_view> optMap;
    if (argc > 1) {
        int32_t i = 1;
        if (argv[1][0] != L'-') {
            optMap[{}] = argv[1];
            i++;
        }
        int32_t waitingIdx = -1;
        for (; i < argc; i++) {
            if (waitingIdx >= 0) {
                optMap[argv[waitingIdx]] = argv[i];
                waitingIdx = -1;
            } else {
                if (wcscmp(argv[i], L"-O0") == 0 || wcscmp(argv[i], L"-O1") == 0 || wcscmp(argv[i], L"--optimize-strict") == 0
                    || wcscmp(argv[i], L"--print-info") == 0 || wcscmp(argv[i], L"--out-legacy-pe") == 0 || wcscmp(argv[i], L"--out-c") == 0
                    || wcscmp(argv[i], L"--version") == 0 || wcscmp(argv[i], L"--help") == 0) {
                    optMap[argv[i]] = {};
                } else if (wcscmp(argv[i], L"--mem-size") == 0 || wcscmp(argv[i], L"-o") == 0) {
                    waitingIdx = i;
                }
            }
        }
    }
    return optMap;
}

static int32_t getMemSize(const std::unordered_map<std::wstring_view, std::wstring_view>& opts) {
    int32_t memSize = 80000000; // default mem size
    if (auto memSizeIt = opts.find(L"--mem-size"); memSizeIt != opts.end()) {
        memSize = std::wcstol(memSizeIt->second.data(), nullptr, 10);
        if (errno == ERANGE || memSize <= 0) {
            throw std::runtime_error("memory size out of range");
        }
    }
    return memSize;
}

int wmain(int argc, wchar_t* argv[]) {
    try {
        auto opts = getOpts(argc, argv);
        if (auto inFilePathIt = opts.find(L""); inFilePathIt == opts.end()) {
            if (opts.contains(L"--version")) {
                std::cout << VER_STR;
            } else if (opts.contains(L"--help")) {
                std::cout << HELP_STR;
            } else {
                throw std::runtime_error("no input file");
            }
        } else {
            std::ifstream input(std::filesystem::path(inFilePathIt->second), std::ios::binary);
            if (!input) {
                throw std::runtime_error("cannot open input file");
            }
            int32_t optimizeLevel = (opts.contains(L"-O1") || !opts.contains(L"-O0")) ? 1 : 0;
            int32_t memSize = getMemSize(opts);
            bool isOptimizeStrict = opts.contains(L"--optimize-strict");
            bool printInfo = opts.contains(L"--print-info");
            bool outModernPE = !opts.contains(L"--out-legacy-pe");
            bool outC = opts.contains(L"--out-c");
            if (auto outFilePathIt = opts.find(L"-o"); outFilePathIt != opts.end()) {
                std::ofstream output(std::filesystem::path(outFilePathIt->second), std::ios::binary);
                if (!output) {
                    throw std::runtime_error("cannot open output file");
                }
                if (outC) {
                    NeoParser::toC(memSize, input, output);
                } else {
                    CodeOptimizer optimizer(NeoParser::parse(input), memSize);
                    optimizer.optimize(optimizeLevel, isOptimizeStrict, printInfo);
                    WindowsPEPlusGenerator generator(optimizer.getBasicBlocks(), optimizer.getTapeSize(), optimizer.getInitOffset());
                    generator.generate(optimizeLevel, outModernPE, printInfo, output);
                }
            } else {
                CodeOptimizer optimizer(NeoParser::parse(input), memSize);
                optimizer.optimize(optimizeLevel, isOptimizeStrict, printInfo);
                WindowsPEPlusGenerator generator(optimizer.getBasicBlocks(), optimizer.getTapeSize(), optimizer.getInitOffset());
                if (optimizeLevel > 0) {
                    generator.rearrangeIRs(printInfo);
                }
                std::cout << "interpreting:\n";
                Interpreter::interpret(generator.getBasicBlocks().front().get(), X64BasicBlock::getGettersForInterpreter(), optimizer.getTapeSize(), optimizer.getInitOffset(), false);
            }
        }
    } catch (std::exception &e) {
        std::cerr << "error: " << e.what() << '\n';
    }
    return 0;
}
